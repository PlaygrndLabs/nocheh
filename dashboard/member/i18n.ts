export type WordKey = keyof typeof memberWords;

export type Translate = (key: WordKey, values?: Record<string, string | number>) => string;
const numbers = new Intl.NumberFormat('en');
/** The page's words, with `{name}` placeholders filled; numbers are written the English way. */
export const translate: Translate = (key, values) =>
  memberWords[key].replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = values?.[name];
    return value === undefined ? whole : typeof value === 'number' ? numbers.format(value) : value;
  });
